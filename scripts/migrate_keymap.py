#!/usr/bin/env python3
"""Generate the initial translation and an auditable per-position mapping.

Usage: python3 scripts/migrate_keymap.py /path/to/corne_choc_pro.keymap [--check]
Only the keymap array and migration manifest are generated; behaviors are C.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYMAP = ROOT / "keyboards/keebart/corne_mx_pro/keymaps/basch_de/keymap.c"
NAMES = ["macos", "num", "sym", "nav", "win", "short", "numpad", "sys"]
KEYS = dict(zip(
    "GRAVE BSLH SPACE SEMI SQT EQUAL COMMA DOT FSLH MINUS BSPC RET ESC TAB COLON TILDE EXCL HASH DLLR PRCNT CARET AMPS ASTRK LPAR RPAR LBKT RBKT LBRC RBRC UNDER QMARK PIPE PLUS PG_UP PG_DN N1 N2 N3 N4 N5 N6 N7 N8 N9 N0 C_VOL_DN C_VOL_UP C_MUTE C_PWR".split(),
    "GRV BSLS SPC SCLN QUOT EQL COMM DOT SLSH MINS BSPC ENT ESC TAB COLN TILD EXLM HASH DLR PERC CIRC AMPR ASTR LPRN RPRN LBRC RBRC LCBR RCBR UNDS QUES PIPE PLUS PGUP PGDN 1 2 3 4 5 6 7 8 9 0 VOLD VOLU MUTE PWR".split()))
KEYS.update({"LCTRL": "LCTL", "RCTRL": "RCTL", "LSHFT": "LSFT", "RSHFT": "RSFT"})
MODS = {"LC": "LCTL", "LG": "LGUI", "LA": "LALT", "LS": "LSFT"}


def kp(expr):
    match = re.fullmatch(r"(LC|LG|LA|LS)\((.*)\)", expr)
    if match:
        return f"{MODS[match[1]]}({kp(match[2])})"
    if expr == "C_VOICE_COMMAND":
        return "KC_ASST"
    if expr == "C_PWR":
        return "KC_PWR"
    return "KC_" + KEYS.get(expr, expr)


def translate(binding):
    behavior, *args = binding[1:].split()
    if behavior == "none": return "KC_NO"
    if behavior == "trans": return "KC_TRNS"
    if behavior == "kp": return kp(args[0])
    if behavior == "tog": return f"TG({args[0]})"
    if behavior in ("hml", "hmr"):
        mod = KEYS.get(args[0], args[0])
        return f"{mod}_T({kp(args[1])})"
    return {
        "&hlt SYS GRAVE": "GRV_SYS", "&mt LA(LC(LG(LSHFT))) LG(SPACE)": "TD(0)",
        "&mt LA(LC(LSHFT)) SQT": "QUOT_CSA", "&lt SHORT EQUAL": "EQ_SHORT",
        "&hlt NAV ESC": "ESC_NAV", "&hlt NUM BSPC": "BSP_NUM", "&rhlt WIN TAB": "TAB_WIN",
        "&rlt NUMPAD RET": "ENT_PAD", "&hlt SYM SPACE": "SPC_SYM", "&lcw SHORT 0": "TD(1)",
        "&mt DOT COMMA": "TD(2)", "&sys_reset": "QK_RBT", "&bootloader": "QK_BOOT",
        "&rgb_ug RGB_HUD": "RM_HUED", "&rgb_ug RGB_HUI": "RM_HUEU",
        "&rgb_ug RGB_SAD": "RM_SATD", "&rgb_ug RGB_SAI": "RM_SATU",
        "&rgb_ug RGB_BRD": "RM_VALD", "&rgb_ug RGB_BRI": "RM_VALU",
        "&rgb_ug RGB_TOG": "RM_TOGG", "&rgb_ug RGB_EFF": "RM_NEXT",
    }.get(binding, "KC_NO" if behavior in ("bt", "ext_power", "studio_unlock") else None)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.source.read_text()
    blocks = re.findall(r'(\w+)_layer\s*\{\s*display-name\s*=\s*"([^"]+)";\s*bindings\s*=\s*<(.*?)>;', source, re.S)
    assert [b[1] for b in blocks] == NAMES, "Unexpected source layer order"
    layers, manifest = [], []
    for name, display, block in blocks:
        bindings = ["&" + " ".join(m.split()) for m in re.findall(r"&([^&]+)", block)]
        assert len(bindings) == 46, (name, len(bindings))
        translated = [translate(b) for b in bindings]
        assert all(t is not None for t in translated), [(b, t) for b, t in zip(bindings, translated) if t is None]
        if name == "sys":
            # Preserve the original mirrored reboot/boot positions, add EE_CLR inward.
            translated[30] = translated[37] = "EE_CLR"
        assert all(translated[i] == "KC_NO" for i in (6, 7, 20, 21))
        layers.append(translated)
        manifest.append({"layer": display, "bindings": [
            {"position": i, "zmk": b, "qmk": t} for i, (b, t) in enumerate(zip(bindings, translated))]})

    text = '// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by scripts/migrate_keymap.py; behavior logic lives in behaviors.c.\n'
    text += '#include QMK_KEYBOARD_H\n#include "behaviors.h"\n\n'
    text += 'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {\n'
    # Logical columns keep the two inner positions and six thumbs visible.
    row_columns = [list(range(14)), list(range(14)), [0,1,2,3,4,5,8,9,10,11,12,13], [3,4,5,8,9,10]]
    for name, cells in zip(NAMES, layers):
        rows = [cells[:14], cells[14:28], cells[28:40], cells[40:]]
        widths = [0] * 14
        for row, columns in zip(rows, row_columns):
            for cell, col in zip(row, columns): widths[col] = max(widths[col], len(cell) + 3)
        text += f'    [{name.upper()}] = LAYOUT_split_3x6_3_ex2(\n'
        for r, (row, columns) in enumerate(zip(rows, row_columns)):
            entries = dict(zip(columns, row))
            line = ''
            for col in range(14):
                cell = entries.get(col)
                value = cell + (',' if r < 3 or col != columns[-1] else '') if cell else ''
                line += value.ljust(widths[col])
            text += '        ' + line.rstrip() + '\n'
        text += '    ),\n'
    text += '};\n\n// Preserve all four manufacturer encoder assignments on every dynamic layer.\n'
    text += '#define ENCODERS { ENCODER_CCW_CW(RGB_MOD, RGB_RMOD), ENCODER_CCW_CW(RGB_HUI, RGB_HUD), \\\n                   ENCODER_CCW_CW(RGB_VAI, RGB_VAD), ENCODER_CCW_CW(RGB_SAI, RGB_SAD) }\n'
    text += 'const uint16_t PROGMEM encoder_map[][NUM_ENCODERS][NUM_DIRECTIONS] = {\n'
    for name in NAMES: text += f'    [{name.upper()}] = ENCODERS,\n'
    text += '};\n'
    outputs = {KEYMAP: text, ROOT / 'docs/bindings.json': json.dumps(manifest, indent=2) + '\n'}
    for path, content in outputs.items():
        if args.check: assert path.read_text() == content, f'{path} differs from source translation'
        else: path.write_text(content)
    print('Verified 8 layers × 46 positions, order, disabled keys, and generated files.')


if __name__ == '__main__': main()
